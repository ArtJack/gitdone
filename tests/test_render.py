import unittest

from helpers import ENGINE, EXAMPLE, ProjectCase
from gitdone import render, table as tables
from gitdone.plan import Plan


def example():
    plan = Plan(EXAMPLE / "plan.json")
    return plan, tables.load_clean(plan)


class Golden(unittest.TestCase):
    def test_the_example_view_is_a_fresh_render(self):
        plan, table = example()
        self.assertEqual(render.normalize((EXAMPLE / "STATUS.md").read_text()), render.normalize(render.status_md(plan, table)))

    def test_the_counts_table_inside_the_example_is_true(self):
        plan, table = example()
        span = render.embedded_counts(plan.doc.read_text())[0]
        lines = plan.doc.read_text().split("\n")
        self.assertEqual("\n".join(lines[span[0]:span[1]]), render.counts_table(plan, table))


class Words(unittest.TestCase):
    def test_the_date_line_is_all_that_normalizing_removes(self):
        a = "# X (generated 2026-01-01)\n\nbody\n"
        b = "# X (generated 2027-12-31)\n\nbody\n"
        self.assertEqual(render.normalize(a), render.normalize(b))
        self.assertNotEqual(render.normalize(a), render.normalize(b + "more"))

    def test_only_the_first_line_is_a_date_line(self):
        a = "# X (generated 2026-01-01)\n# Y (generated 2026-01-01)\n"
        b = "# X (generated 2026-01-01)\n# Y (generated 2027-01-01)\n"
        self.assertNotEqual(render.normalize(a), render.normalize(b))

    def test_a_zero_between_the_first_and_last_columns_stays_blank(self):
        plan, table = example()
        row = next(line for line in render.counts_table(plan, table).split("\n") if line.startswith("| 4 |"))
        self.assertEqual(row, "| 4 | Reporting | 3 | 0 |  |  |  | 3 |")

    def test_group_rows_and_the_all_row(self):
        plan, table = example()
        lines = render.counts_table(plan, table).split("\n")
        self.assertIn("| | **Launch** | **11** | **4** | **2** | **1** | **2** | **2** |", lines)
        self.assertIn("| | **Later** | **5** |  |  |  | **1** | **4** |", lines)
        self.assertEqual(lines[-1], "| | **All** | **16** | **4** | **2** | **1** | **3** | **6** |")

    def test_the_summary_style_names_only_the_kinds_it_has(self):
        plan, table = example()
        self.assertIn("(partial 1, not built 4)", render.status_md(plan, table))

    def test_a_product_with_a_row_range_is_measured(self):
        plan, table = example()
        view = render.status_md(plan, table)
        self.assertIn("| Lending (rows 5–8) | 1 live, 1 built, 1 demo, 1 not built | strict 25%, weighted 57% |", view)

    def test_a_product_with_a_group_and_chosen_measures(self):
        plan, table = example()
        self.assertIn("| Kiosk, Later (5) | barely started | weighted 8% |", render.status_md(plan, table))

    def test_a_static_product_is_copied(self):
        plan, table = example()
        self.assertIn("| Library website | not in this scope | none |", render.status_md(plan, table))

    def test_the_opener(self):
        plan, table = example()
        self.assertEqual(
            render.opener(plan, table),
            "Launch: strict 36% (4/11), weighted 63% · Later: strict 0% (0/5), weighted 8% · "
            "next: S1 (Reading lists and renewals), needs the head librarian's word at release")


class Configuration(ProjectCase):
    """Everything the view says about a project comes from the plan."""

    def view(self):
        plan = self.plan()
        return render.status_md(plan, tables.load_clean(plan))

    def test_title_noun_scale_and_generator(self):
        self.change_plan(title="Other", noun="things", scale="Own words.", generated_by="my-tool", regenerate="my-tool go")
        view = self.view()
        self.assertTrue(view.startswith("# Other (generated "))
        self.assertIn("## Bramble Kiosk, Launch: 11 things", view)
        self.assertIn("> **Scale.** Own words.", view)
        self.assertIn("Generated by `my-tool`", view)
        self.assertIn("run `my-tool go`", view)

    def test_kinds_and_their_weights(self):
        data = json.loads(self.plan_path.read_text())
        data["kinds"][4]["weight"] = 0.1
        data["kinds"][0]["short"] = "On"
        self.change_plan(kinds=data["kinds"])
        view = self.view()
        self.assertIn("| Domain | Rows | On | Built |", view)
        self.assertIn("- **Weighted:** `█████████████░░░░░░░` 65%", view)

    def test_groups(self):
        self.change_plan(groups=[{"id": "a", "label": "First", "domains": "1-2", "total": 8},
                                 {"id": "b", "label": "Second", "domains": [3, 4, 5], "total": 8}],
                         sections=[{"type": "group", "group": "b"}], products=[])
        self.assertIn("## Second: 8 capabilities", self.view())

    def test_a_section_title(self):
        data = json.loads(self.plan_path.read_text())
        data["sections"][4]["title"] = "Questions for the board"
        self.change_plan(sections=data["sections"])
        self.assertIn("## Questions for the board", self.view())

    def test_every_workstream_done(self):
        for number in (3, 6, 7, 8, 10, 11):
            self.set_row(number, "Live", f"`{self.sha_main[:7]}`")
        view = self.view()
        self.assertIn("**Next, in order:** nothing; every workstream is fully live.", view)
        plan = self.plan()
        self.assertIn("every workstream is fully live", render.opener(plan, tables.load_clean(plan)))

    def test_a_plan_with_only_a_status_doc(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = pathlib.Path(tmp)
            (root / "t.md").write_text("### 1. A (2)\n\n| 1 | a | Live | x |\n| 2 | b | Not built | |\n")
            (root / "plan.json").write_text(json.dumps({"status_doc": "t.md"}))
            plan = Plan(root / "plan.json")
            table = tables.load_clean(plan)
            view = render.status_md(plan, table)
            self.assertIn("## Status: 2 rows", view)
            self.assertIn("*Strict* counts only rows that are Live. *Weighted* gives: Live 1 · Built, not live 0.8 ·", view)
            self.assertEqual(render.opener(plan, table), "All: strict 50% (1/2), weighted 50% · next: row 2 (b)")
            self.assertIn("## What is left: 1 of 2 rows", view)
            self.assertIn("| 2 | b | Not built |  |", view)
            self.assertIn("## Live: 1 of 2 rows", view)
            self.assertIn("| 1 | a | x |", view)
            self.assertEqual(render.counts_table(plan, table).split("\n")[-1], "| | **All** | **2** | **1** |  |  | **1** |")


class Stops(ProjectCase):
    def assert_render_stops(self, words):
        code, out, err = self.cli("render")
        self.assertEqual(code, 2, err)
        self.assertEqual(out, "")
        self.assertIn(words, err)

    def test_an_unknown_status(self):
        self.set_row(9, "Almost", "soon", view=False)
        self.assert_render_stops("row 9: unknown status 'Almost'")

    def test_a_group_total_that_does_not_sum(self):
        data = json.loads(self.plan_path.read_text())
        data["groups"][0]["total"] = 12
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("group Launch: its domains hold 11 rows, the plan says 12")

    def test_a_total_that_does_not_sum(self):
        data = json.loads(self.plan_path.read_text())
        data["rows_total"] = 17
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("the table has 16 rows, the plan says 17")

    def test_a_workstream_naming_a_row_that_is_not_there(self):
        data = json.loads(self.plan_path.read_text())
        data["workstreams"][0]["rows"] = [99]
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("workstream S1 names row 99")

    def test_an_order_naming_a_workstream_that_is_not_there(self):
        data = json.loads(self.plan_path.read_text())
        data["order"] = ["S9"]
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("order names 'S9'")

    def test_a_domain_in_no_group(self):
        data = json.loads(self.plan_path.read_text())
        data["groups"][1]["domains"] = "4"
        data["groups"][1]["total"] = 3
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("domain 5 (Accessibility) is in no group")

    def test_a_domain_in_two_groups(self):
        data = json.loads(self.plan_path.read_text())
        data["groups"][1]["domains"] = "3-5"
        data["groups"][1]["total"] = 8
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("domain 3 is in two groups")

    def test_a_section_that_is_missing_a_key(self):
        data = json.loads(self.plan_path.read_text())
        del data["sections"][2]["columns"]
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("a table section needs 'columns'")

    def test_a_section_naming_a_group_that_is_not_there(self):
        data = json.loads(self.plan_path.read_text())
        data["sections"][0]["group"] = "nowhere"
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("no group has the id 'nowhere'")

    def test_a_workstream_without_an_id(self):
        data = json.loads(self.plan_path.read_text())
        data["workstreams"].append({"name": "x"})
        self.plan_path.write_text(json.dumps(data))
        self.assert_render_stops("each one needs an id")

    def test_a_plan_that_is_not_json(self):
        self.plan_path.write_text("{")
        self.assert_render_stops("is not valid JSON")

    def test_a_missing_table(self):
        self.table_path.unlink()
        self.assert_render_stops("cannot read the status table")


class Commands(ProjectCase):
    def test_a_hook_under_a_bare_locale_still_writes_the_view(self):
        env = {**os.environ, "LC_ALL": "C", "LANG": "C", "PYTHONUTF8": "0", "PYTHONCOERCECLOCALE": "0"}
        self.view_path.unlink()
        for args in (["render", "--write"], ["render"], ["counts"], ["check", "--offline"], ["opener"]):
            done = subprocess.run([sys.executable, str(ENGINE), *args, "--plan", str(self.plan_path)],
                                  env=env, capture_output=True)
            self.assertEqual(done.returncode, 0, done.stderr)
        self.assertIn("█".encode("utf-8"), self.view_path.read_bytes())

    def test_a_reader_that_stops_early_is_not_an_error(self):
        done = subprocess.run(f"'{sys.executable}' '{ENGINE}' render --plan '{self.plan_path}' | head -1", shell=True,
                              capture_output=True, text=True)
        self.assertTrue(done.stdout.startswith("# Bramble Kiosk tracker"))
        self.assertEqual(done.stderr, "")

    def test_render_prints_the_view_and_writes_it(self):
        self.view_path.unlink()
        code, out, _ = self.cli("render")
        self.assertEqual(code, 0)
        self.assertTrue(out.startswith("# Bramble Kiosk tracker (generated "))
        self.assertFalse(self.view_path.exists())
        code, out, _ = self.cli("render", "--write")
        self.assertEqual(code, 0)
        self.assertIn("wrote", out)
        self.assertTrue(self.view_path.exists())

    def test_counts_prints_and_updates_the_table(self):
        self.set_row(9, "Partial", "x", view=False)
        text = self.table_path.read_text()
        self.table_path.write_text(text.replace("| 3 | Accounts | 3 | 0 |  |  | 2 | 1 |", "| 3 | Accounts | 3 | 7 |  |  | 2 | 1 |"))
        code, _, _ = self.cli("counts", "--write")
        self.assertEqual(code, 0)
        self.assertIn("| 3 | Accounts | 3 | 0 |  |  | 2 | 1 |", self.table_path.read_text())

    def test_counts_write_without_a_table_to_update(self):
        text = self.table_path.read_text()
        start = text.index("| # | Domain")
        end = text.index("## Launch")
        self.table_path.write_text(text[:start] + text[end:])
        code, _, err = self.cli("counts", "--write")
        self.assertEqual(code, 2)
        self.assertIn("holds no counts table", err)


